def solve(data):
    author_id, message = data.split("|", 1)
    author_id = int(author_id)
    if author_id in white_ids:
        return ["OK", "clean"]
    if len (message) == 0:
        return ["suspicious", "empty"]
    if len (message) < 5:
        return ["suspicious", "short"]
    if "http" in message:
        return ["suspicious", "bad words"]
    for word in bad_words:
        if word.lower() in message.lower():
            return ["suspicious", "bad words"]
    for ch in letters_greek_set:
        if ch in message:
            return ["spam", "greek"]
    for word in spam_words:
        if word in message:
            return ["spam", "spam words"]

    return ["OK", "clean"]

